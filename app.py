@st.cache_resource
def load_model_and_metadata():
    """
    Load persisted model pipeline and evaluation metrics once into memory.
    Never retrains on user submission.
    """
    model_path = os.path.join(PROJECT_ROOT, "models", "model.pkl")
    metrics_path = os.path.join(PROJECT_ROOT, "models", "metrics.json")
    
    if not os.path.exists(model_path):
        st.error(f"Model file not found at `{model_path}`. Please run `python src/train.py` first.")
        st.stop()
        
    model = joblib.load(model_path)
    
    metrics = {}
    if os.path.exists(metrics_path):
        with open(metrics_path, "r", encoding="utf-8") as f:
            metrics = json.load(f)
            
    return model, metrics

# Load artifacts
model_pipeline, metrics_data = load_model_and_metadata()
classes_list = list(model_pipeline.classes_)

