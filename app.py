# TAB 2: BULK CSV CLASSIFICATION
# -------------------------------------------------------------
with tab2:
    st.subheader("Bulk Ticket Ingestion & Automated Triage")
    st.write("Upload a CSV file of customer tickets to classify multiple inquiries simultaneously and export the routing manifest.")
    
    # Template download
    sample_csv = pd.DataFrame({
        "ticket_id": ["TCK-9001", "TCK-9002", "TCK-9003", "TCK-9004", "TCK-9005"],
        "text": [
            "I was charged $45 unexpectedly on my Mastercard.",
            "The iOS app crashes every time I open the camera scanner.",
            "Can I get a prepaid shipping return label for my RMA?",
            "I forgot my password and cannot sign in to the portal.",
            "What are your business support working hours on weekends?"
        ]
    }).to_csv(index=False).encode("utf-8")
    
    st.download_button(
        "📥 Download Sample CSV Template",
        data=sample_csv,
        file_name="sample_support_tickets.csv",
        mime="text/csv",
        help="Download a ready-to-test CSV template."
    )
    
    uploaded_file = st.file_uploader("Upload Ticket File (CSV format)", type=["csv"])
    
    if uploaded_file is not None:
        try:
            bulk_df = pd.read_csv(uploaded_file)
            st.write(f"Loaded **{len(bulk_df)}** records from `{uploaded_file.name}`.")
            st.dataframe(bulk_df.head(5), use_container_width=True)
            
            # Select text column
            possible_cols = [c for c in bulk_df.columns if "text" in c.lower() or "desc" in c.lower() or "ticket" in c.lower() or "message" in c.lower()]
            default_col = possible_cols[0] if possible_cols else bulk_df.columns[0]
            
            text_column = st.selectbox("Select the column containing ticket text:", bulk_df.columns, index=list(bulk_df.columns).index(default_col))
            
            if st.button("⚡ Run Bulk Triage", type="primary"):
                with st.spinner("Processing tickets through NLP pipeline..."):
                    # Process in batch
                    clean_series = bulk_df[text_column].fillna("").astype(str).apply(preprocess_text)
                    
                    # Filter empty for prediction safely
                    pred_categories = []
                    confidences = []
                    departments = []
                    review_flags = []
                    
                    for raw_t, clean_t in zip(bulk_df[text_column], clean_series):
                        if not clean_t or len(clean_t.strip()) == 0:
                            pred_categories.append("Unassigned")
                            confidences.append(0.0)
                            departments.append("Manual Triage Queue")
                            review_flags.append("Needs Review (Empty/Invalid)")
                        else:
                            probs = model_pipeline.predict_proba([clean_t])[0]
                            top_idx = int(np.argmax(probs))
                            cat = classes_list[top_idx]
                            conf = float(probs[top_idx])
                            
                            pred_categories.append(cat)
                            confidences.append(round(conf, 4))
                            
                            if conf >= confidence_threshold:
                                departments.append(DEPARTMENT_ROUTING.get(cat, "General Support"))
                                review_flags.append("Auto-Routed")
                            else:
                                departments.append("Manual Review Queue")
                                review_flags.append("Needs Review (Low Confidence)")
                                
                    bulk_df["Cleaned_Text"] = clean_series
                    bulk_df["Predicted_Category"] = pred_categories
                    bulk_df["Confidence"] = confidences
                    bulk_df["Routed_Department"] = departments
                    bulk_df["Triage_Status"] = review_flags
                    
                    st.success(f"Successfully processed {len(bulk_df)} tickets!")
                    
                    # Summary metrics
                    b_col1, b_col2, b_col3 = st.columns(3)
                    auto_count = sum(1 for f in review_flags if f == "Auto-Routed")
                    b_col1.metric("Total Ingested", len(bulk_df))
                    b_col2.metric("Auto-Routed", f"{auto_count} ({auto_count/len(bulk_df)*100:.1f}%)")
                    b_col3.metric("Flagged for Review", f"{len(bulk_df) - auto_count} ({(len(bulk_df) - auto_count)/len(bulk_df)*100:.1f}%)")
                    
                    st.dataframe(bulk_df, use_container_width=True)
                    
                    # Export button
                    export_csv = bulk_df.to_csv(index=False).encode("utf-8")
                    st.download_button(
                        "💾 Export Processed Triage Results (CSV)",
                        data=export_csv,
                        file_name="classified_support_tickets_output.csv",
                        mime="text/csv"
                    )
        except Exception as e:
            st.error(f"Error processing uploaded CSV: {e}")

