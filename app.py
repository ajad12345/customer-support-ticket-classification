# TAB 1: LIVE SINGLE TICKET TRIAGE
# -------------------------------------------------------------
with tab1:
    st.subheader("Interactive Support Ticket Classifier")
    st.write("Enter an incoming customer support ticket message below to simulate real-time routing:")
    
    # Pre-canned quick sample buttons
    st.markdown("**Or load a pre-configured scenario:**")
    sample_cols = st.columns(4)
    sample_text = ""
    
    if sample_cols[0].button("💳 Billing Inquiry"):
        sample_text = "I was charged $89 on my credit card, but my subscription was supposed to be cancelled last month."
    if sample_cols[1].button("🛠️ Technical Crash"):
        sample_text = "The application crashes every time I click the Export to PDF button on macOS with error 500."
    if sample_cols[2].button("🔐 Locked Account"):
        sample_text = "I am locked out of my corporate account and the 2FA SMS code is not arriving on my mobile."
    if sample_cols[3].button("📦 Negated Delivery"):
        sample_text = "The courier marked the package as delivered, but I have NOT received any delivery at my address."
        
    user_input = st.text_area(
        "Customer Ticket Text:",
        value=sample_text,
        height=120,
        placeholder="Type or paste the customer support request here... (e.g., 'I ordered a replacement part but received the wrong size.')"
    )
    
    classify_btn = st.button("🚀 Analyze & Route Ticket", type="primary")
    
    if classify_btn or (sample_text and user_input == sample_text):
        if not user_input or len(user_input.strip()) < 3:
            st.error("❌ **Invalid Input**: Please enter a valid customer support message (at least 3 characters).")
        else:
            # 1. Shared Preprocessing
            cleaned_text = preprocess_text(user_input)
            
            if not cleaned_text or len(cleaned_text.strip()) == 0:
                st.error("❌ **Validation Failed**: The input contained no meaningful words after removing symbols and stopwords. Please provide more detail.")
            else:
                # 2. Model Prediction
                probabilities = model_pipeline.predict_proba([cleaned_text])[0]
                pred_idx = int(np.argmax(probabilities))
                pred_category = classes_list[pred_idx]
                confidence = float(probabilities[pred_idx])
                
                # Check confidence gate
                is_confident = confidence >= confidence_threshold
                assigned_dept = DEPARTMENT_ROUTING.get(pred_category, "General Support")
                cat_icon = CATEGORY_ICONS.get(pred_category, "📁")
                
                st.markdown("---")
                st.subheader("🎯 Triage & Routing Results")
                
                # Metric Cards
                m_col1, m_col2, m_col3, m_col4 = st.columns(4)
                
                m_col1.metric("Predicted Category", f"{cat_icon} {pred_category}")
                m_col2.metric("Confidence Score", f"{confidence * 100:.1f}%")
                
                if is_confident:
                    m_col3.metric("Auto-Route Status", "✅ Approved", delta="High Confidence")
                    m_col4.metric("Routed To", assigned_dept)
                else:
                    m_col3.metric("Auto-Route Status", "⚠️ Gated", delta="Below Threshold", delta_color="inverse")
                    m_col4.metric("Routed To", "Manual Review Queue")
                    
                # Routing Decision Callout
                if is_confident:
                    st.success(
                        f"**Routing Confirmation**: This ticket has been automatically dispatched to **{assigned_dept}** "
                        f"with **{confidence * 100:.1f}%** confidence."
                    )
                else:
                    st.warning(
                        f"⚠️ **Low Confidence Warning**: The highest confidence category is **{pred_category}** ({confidence*100:.1f}%), "
                        f"which is below the threshold of **{confidence_threshold*100:.0f}%**. "
                        f"To prevent incorrect dispatch, this request has been routed to **Manual Review & Human Triage**."
                    )
                    
                # Expandable Preprocessing Inspection
                with st.expander("🔍 View NLP Preprocessing & Feature Extraction Details"):
                    prep_col1, prep_col2 = st.columns(2)
                    prep_col1.markdown("**Raw Input Text:**")
                    prep_col1.code(user_input, language="text")
                    prep_col2.markdown("**Normalized & Lemmatized Tokens (Negation-Preserved):**")
                    prep_col2.code(cleaned_text, language="text")
                    st.caption("Preprocessing applied: Lowercasing → Regex cleaning (URLs/Emails/IDs) → Negation preservation → Lemmatization.")
                    
                # Confidence Distribution Horizontal Bar Chart
                st.markdown("#### Probability Distribution Across All Categories")
                prob_df = pd.DataFrame({
                    "Category": classes_list,
                    "Probability": [p * 100 for p in probabilities]
                }).sort_values(by="Probability", ascending=True)
                
                st.bar_chart(data=prob_df.set_index("Category"), horizontal=True)

