    st.markdown("""
    ### Why Macro-F1 Over Accuracy Alone?
    In customer support triage, simple accuracy can be deceptive if certain inquiry types have different frequencies. 
    **Macro-F1** treats every category with equal importance by calculating the unweighted arithmetic mean of F1-scores across all classes. 
    Selecting our final model on Macro-F1 guarantees that no critical department (such as *Account Access* or *Refund/Returns*) 
    suffers from undetected misclassifications.
    
    ### Why Fit the Vectorizer ONLY on Training Data?
    Fitting a TF-IDF vectorizer or vocabulary index on the entire dataset prior to splitting constitutes **data leakage**. 
    Information from the test set (such as inverse document frequencies and vocabulary existence) would contaminate the training process, 
    artificially inflating evaluation scores. By embedding `TfidfVectorizer` inside an encapsulated scikit-learn `Pipeline`, 
    we ensure the vectorizer is fitted strictly on the training partition during both cross-validation folds and final model fitting.
    """)
